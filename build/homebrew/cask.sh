#!/usr/bin/env sh
# Render the Homebrew cask for Lathe.app to stdout.
#
#   build/homebrew/cask.sh <version> <sha256-of-the-zip> > Casks/lathe.rb
#
# release.yml commits the output to devenjarvis/homebrew-tap. This is written
# here rather than by GoReleaser's `homebrew_casks` because the `app` stanza
# (and app bundles) are GoReleaser Pro-only; the OSS generator can only emit a
# `binary` from a GoReleaser-built archive.
#
# The cask installs Lathe.app into /Applications and links the CLI from inside
# the bundle, so `lathe` on the terminal is the same signed binary as the app.
# No quarantine-stripping postflight: the app is Developer ID signed, notarized
# and stapled, so Gatekeeper accepts it as downloaded.
set -eu

version=${1:?usage: cask.sh <version> <sha256>}
version=${version#v}
sha256=${2:?usage: cask.sh <version> <sha256>}

cat <<EOF
# This file was generated by devenjarvis/lathe's release workflow
# (build/homebrew/cask.sh). DO NOT EDIT.
cask "lathe" do
  version "${version}"
  sha256 "${sha256}"

  url "https://github.com/devenjarvis/lathe/releases/download/v#{version}/Lathe_#{version}_macos_universal.zip"
  name "Lathe"
  desc "Generate, store, serve, verify, and extend hands-on technical tutorials"
  homepage "https://github.com/devenjarvis/lathe"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on macos: ">= :monterey"

  app "Lathe.app"
  binary "#{appdir}/Lathe.app/Contents/MacOS/lathe"

  # Tutorials in ~/.lathe are the user's data and are deliberately not zapped.
  zap trash: [
    "~/Library/Caches/com.devenjarvis.lathe",
    "~/Library/HTTPStorages/com.devenjarvis.lathe",
    "~/Library/Preferences/com.devenjarvis.lathe.plist",
    "~/Library/Saved Application State/com.devenjarvis.lathe.savedState",
    "~/Library/WebKit/com.devenjarvis.lathe",
  ]
end
EOF
